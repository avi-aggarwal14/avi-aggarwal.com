// Tiny 5x5 block font for the console easter egg (lower-case letters only).
const FONT: Record<string, string[]> = {
  a: [' ### ', '#   #', '#####', '#   #', '#   #'],
  b: ['#### ', '#   #', '#### ', '#   #', '#### '],
  c: [' ####', '#    ', '#    ', '#    ', ' ####'],
  d: ['#### ', '#   #', '#   #', '#   #', '#### '],
  e: ['#####', '#    ', '#### ', '#    ', '#####'],
  f: ['#####', '#    ', '#### ', '#    ', '#    '],
  g: [' ####', '#    ', '#  ##', '#   #', ' ####'],
  h: ['#   #', '#   #', '#####', '#   #', '#   #'],
  i: ['#####', '  #  ', '  #  ', '  #  ', '#####'],
  j: ['#####', '   # ', '   # ', '#  # ', ' ##  '],
  k: ['#   #', '#  # ', '###  ', '#  # ', '#   #'],
  l: ['#    ', '#    ', '#    ', '#    ', '#####'],
  m: ['#   #', '## ##', '# # #', '#   #', '#   #'],
  n: ['#   #', '##  #', '# # #', '#  ##', '#   #'],
  o: [' ### ', '#   #', '#   #', '#   #', ' ### '],
  p: ['#### ', '#   #', '#### ', '#    ', '#    '],
  q: [' ### ', '#   #', '# # #', '#  # ', ' ## #'],
  r: ['#### ', '#   #', '#### ', '#  # ', '#   #'],
  s: [' ####', '#    ', ' ### ', '    #', '#### '],
  t: ['#####', '  #  ', '  #  ', '  #  ', '  #  '],
  u: ['#   #', '#   #', '#   #', '#   #', ' ### '],
  v: ['#   #', '#   #', '#   #', ' # # ', '  #  '],
  w: ['#   #', '#   #', '# # #', '## ##', '#   #'],
  x: ['#   #', ' # # ', '  #  ', ' # # ', '#   #'],
  y: ['#   #', ' # # ', '  #  ', '  #  ', '  #  '],
  z: ['#####', '   # ', '  #  ', ' #   ', '#####'],
  ' ': ['     ', '     ', '     ', '     ', '     '],
};

/** Render a word as 5-row block letters (unknown characters become blanks). */
export function asciiBanner(text: string): string {
  const rows = ['', '', '', '', ''];
  for (const ch of text.toLowerCase()) {
    const glyph = FONT[ch] ?? FONT[' '];
    for (let r = 0; r < 5; r++) rows[r] += glyph[r] + '  ';
  }
  return '\n' + rows.map((r) => r.replace(/\s+$/, '')).join('\n') + '\n';
}
